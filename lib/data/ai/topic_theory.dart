  static bool hasTopic(String topicId) =>
      _items.any((item) => item.topicId == topicId);

  static List<String> get topics => _items.map((item) => item.topicId).toList();

  static TopicTheory? forTopic(String topicId, {required bool isKz}) {
    final topic = TopicCatalog.byName(topicId);
    final id = topic?.id ?? topicId;
    for (final item in _items) {
      if (item.topicId == id) return item.toTheory(isKz);
    }
    return null;
  }
