import 'topic_catalog.dart';

class TopicTheory {
  final String idea;
  final List<String> points;
  final String pitfall;

  const TopicTheory({
    required this.idea,
    required this.points,
    required this.pitfall,
  });
}

class _TheoryItem {
  final String topicId;
  final String ideaKk;
  final String ideaRu;
  final List<String> pointsKk;
  final List<String> pointsRu;
  final String pitfallKk;
  final String pitfallRu;

  const _TheoryItem(
    this.topicId,
    this.ideaKk,
    this.ideaRu,
    this.pointsKk,
    this.pointsRu,
    this.pitfallKk,
    this.pitfallRu,
  );

  TopicTheory toTheory(bool isKz) => TopicTheory(
        idea: isKz ? ideaKk : ideaRu,
        points: isKz ? pointsKk : pointsRu,
        pitfall: isKz ? pitfallKk : pitfallRu,
      );
}

