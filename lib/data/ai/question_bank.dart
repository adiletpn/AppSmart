class _BankItem {
  final String topicId;
  final String promptKk;
  final String promptRu;
  final List<String> optionsKk;
  final List<String> optionsRu;
  final String explanationKk;
  final String explanationRu;

  const _BankItem(
    this.topicId,
    this.promptKk,
    this.promptRu,
    this.optionsKk,
    this.optionsRu,
    this.explanationKk,
    this.explanationRu,
  );

  QuizQuestion toQuestion(int order, bool isKz, Random random) {
    final source = isKz ? optionsKk : optionsRu;
    final correct = source.first;
    final options = [...source]..shuffle(random);
    return QuizQuestion(
      id: '$topicId-$order',
      topic: TopicCatalog.byName(topicId)?.name(isKz) ?? topicId,
      prompt: isKz ? promptKk : promptRu,
      options: options,
      correctIndex: options.indexOf(correct),
      explanation: isKz ? explanationKk : explanationRu,
    );
  }
}

