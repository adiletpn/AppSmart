import '../models/study_task.dart';

class TaskContent {
  final String statement;
  final List<TaskExample> examples;
  final String hint;
  final String solution;

  const TaskContent({
    required this.statement,
    required this.examples,
    required this.hint,
    required this.solution,
  });
}

class _ContentItem {
  final String topicId;
  final String statementKk;
  final String statementRu;
  final List<TaskExample> examples;
  final String hintKk;
  final String hintRu;
  final String solutionKk;
  final String solutionRu;

  const _ContentItem(
    this.topicId,
    this.statementKk,
    this.statementRu,
    this.examples,
    this.hintKk,
    this.hintRu,
    this.solutionKk,
    this.solutionRu,
  );

  TaskContent toContent(bool isKz) => TaskContent(
        statement: isKz ? statementKk : statementRu,
        examples: examples,
        hint: isKz ? hintKk : hintRu,
        solution: isKz ? solutionKk : solutionRu,
      );
}

